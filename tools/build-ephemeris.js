// Builds src/ephdata.js for src/ephemeris.js: VSOP87B (Earth, Mercury, Venus, Mars) and ELP/MPP02
// from the astronomia package, slimmed by dropping the smallest terms while the summed worst case of
// everything dropped stays inside a budget, plus the Chebyshev tables and Delta T in tools/data.
// Run from a folder that has astronomia installed: node build-ephemeris.js <out.js>
const fs = require('fs'), path = require('path');
const base = path.dirname(require.resolve('astronomia/package.json')) + '/lib/data/';
const ARCSEC = Math.PI / 180 / 3600;
function slim(series, tmax, budget) {
  // series: { '0': [[A, ...], ...], '1': [...], ... }  term value ~ A * T^k
  const all = [];
  for (const [k, terms] of Object.entries(series)) terms.forEach((t, i) => all.push({ k, i, eff: Math.abs(t[0]) * Math.pow(tmax, +k) }));
  all.sort((a, b) => a.eff - b.eff);
  let sum = 0; const drop = new Set();
  for (const x of all) { if (sum + x.eff > budget) break; sum += x.eff; drop.add(x.k + ':' + x.i); }
  const res = {};
  for (const [k, terms] of Object.entries(series)) res[k] = terms.filter((t, i) => !drop.has(k + ':' + i));
  return res;
}
const load = (f) => { const m = require(base + f); return m.default || m; };
const pack = { vsop: {} };
for (const p of ['earth', 'mercury', 'venus', 'mars']) {
  const d = load('vsop87B' + p + '.cjs'), T = 0.2;   // millennia from J2000: 1800-2200
  pack.vsop[p] = { name: d.name, type: d.type, L: slim(d.L, T, 0.05 * ARCSEC), B: slim(d.B, T, 0.05 * ARCSEC), R: slim(d.R, T, 2.5e-7) };
}
{
  const d = load('elpMppDeFull.cjs'), T = 2.5;   // centuries from J2000: 1750-2250 (arcsec, arcsec, km)
  // Latitude gets a tighter budget: the true node depends on the Moon's latitude speed.
  pack.elp = { name: d.name, W1: d.W1, L: slim(d.L, T, 1), B: slim(d.B, T, 0.3), R: slim(d.R, T, 2) };
}
pack.outer = JSON.parse(fs.readFileSync(path.join(__dirname, 'data/outer.json')));
pack.deltat = JSON.parse(fs.readFileSync(path.join(__dirname, 'data/deltat.json')));
const txt = JSON.stringify(pack, (k, v) => (typeof v === 'number' && !Number.isInteger(v) ? +v.toPrecision(12) : v));
fs.writeFileSync(process.argv[2], '// Ephemeris data for ephemeris.js. Generated by tools/build-ephemeris.js; do not edit.\n' +
  '// VSOP87 and ELP/MPP02 series from the astronomia package (MIT); Chebyshev tables fitted to NASA JPL DE431.\n' +
  'const HD_EPH = ' + txt + ';\n');
console.log('wrote', process.argv[2], (txt.length / 1024).toFixed(0) + ' KB');
